package web_test

import (
	"io/fs"
	"strings"
	"testing"

	"simplefs/web"
)

func TestAssets_EmbeddedFiles(t *testing.T) {
	requiredFiles := []string{
		"templates/index.html",
		"templates/file_list.html",
		"templates/details_modal.html",
		"templates/preview_modal.html",
		"templates/login.html",
		"static/favicon.svg",
		"static/app-icon.svg",
		"static/apple-touch-icon.png",
	}

	for _, file := range requiredFiles {
		data, err := fs.ReadFile(web.Assets, file)
		if err != nil {
			t.Errorf("failed to read embedded file %q: %v", file, err)
		}
		if len(data) == 0 {
			t.Errorf("embedded file %q is empty", file)
		}
	}
}

func TestAssets_IconSpriteContainsBackendIcons(t *testing.T) {
	sprite, err := fs.ReadFile(web.Assets, "static/icons.svg")
	if err != nil {
		t.Skip("icons.svg is generated by `pnpm run build:icons`")
	}
	backendIcons := []string{
		"folder", "move_to_inbox", "outbox", "download", "folder_code", "perm_media", "topic", "terminal",
		"description", "image", "picture_as_pdf", "table_chart", "article", "movie", "music_note", "folder_zip", "code",
	}
	for _, icon := range backendIcons {
		if !strings.Contains(string(sprite), `id="`+icon+`"`) {
			t.Errorf("icons.svg is missing %q; update scripts/build-icons.mjs patterns", icon)
		}
	}
}
